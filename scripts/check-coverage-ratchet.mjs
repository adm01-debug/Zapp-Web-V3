#!/usr/bin/env node
/**
 * E45 — Coverage Ratchet Gate
 *
 * Reads the vitest v8 coverage JSON (coverage/coverage-summary.json) and
 * compares it against a committed baseline (scripts/coverage-baseline.json).
 * Blocks CI if overall coverage drops below the baseline thresholds.
 *
 * Usage:
 *   node scripts/check-coverage-ratchet.mjs           # check mode (CI)
 *   node scripts/check-coverage-ratchet.mjs --update  # update baseline from current coverage
 *
 * The baseline is updated manually after deliberate coverage improvements.
 * Never auto-update in CI — that defeats the ratchet.
 *
 * Coverage file location: coverage/coverage-summary.json
 * This file is generated by: npm run test -- --coverage
 * Or: NODE_OPTIONS=--max-old-space-size=6144 vitest run --coverage
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const UPDATE_MODE = process.argv.includes('--update');
const COVERAGE_FILE = 'coverage/coverage-summary.json';
const BASELINE_FILE = 'scripts/coverage-baseline.json';

// Ratchet tolerance: allow up to this many percentage points drop before
// failing. Set to 0 for strict ratchet, higher for noisy suites.
// We use 0.5% tolerance to handle floating-point/run-to-run variation.
const TOLERANCE_PCT = 0.5;

// Minimum acceptable coverage floor — even if baseline is somehow corrupted,
// we never let coverage drop below these absolute minimums.
const ABSOLUTE_FLOOR = {
  statements: 20,
  branches: 15,
  functions: 20,
  lines: 20,
};

function readJson(path) {
  try {
    return JSON.parse(readFileSync(path, 'utf8'));
  } catch (e) {
    return null;
  }
}

function extractTotals(summary) {
  const total = summary?.total;
  if (!total) return null;
  return {
    statements: total.statements?.pct ?? 0,
    branches: total.branches?.pct ?? 0,
    functions: total.functions?.pct ?? 0,
    lines: total.lines?.pct ?? 0,
    statementsCount: total.statements?.total ?? 0,
    coveredStatements: total.statements?.covered ?? 0,
    uncoveredLines: (total.lines?.total ?? 0) - (total.lines?.covered ?? 0),
  };
}

if (UPDATE_MODE) {
  if (!existsSync(COVERAGE_FILE)) {
    console.error(`❌ ${COVERAGE_FILE} not found. Run: npm run test -- --coverage`);
    process.exit(1);
  }
  const summary = readJson(COVERAGE_FILE);
  const totals = extractTotals(summary);
  if (!totals) {
    console.error(`❌ Could not parse ${COVERAGE_FILE}. Invalid format.`);
    process.exit(1);
  }

  const baseline = {
    _generated: new Date().toISOString(),
    _note: 'Updated via: node scripts/check-coverage-ratchet.mjs --update. Never commit regressions.',
    statements: totals.statements,
    branches: totals.branches,
    functions: totals.functions,
    lines: totals.lines,
    uncoveredLines: totals.uncoveredLines,
    totalStatements: totals.statementsCount,
  };

  writeFileSync(BASELINE_FILE, JSON.stringify(baseline, null, 2) + '\n');
  console.log(`✅ Coverage baseline updated:`);
  console.log(`   Statements : ${totals.statements.toFixed(1)}%`);
  console.log(`   Branches   : ${totals.branches.toFixed(1)}%`);
  console.log(`   Functions  : ${totals.functions.toFixed(1)}%`);
  console.log(`   Lines      : ${totals.lines.toFixed(1)}%`);
  console.log(`\nBaseline written to ${BASELINE_FILE}`);
  process.exit(0);
}

// Check mode
if (!existsSync(COVERAGE_FILE)) {
  console.log(`ℹ️  ${COVERAGE_FILE} not found — coverage ratchet skipped.`);
  console.log('   Run with --coverage to generate: npm run test -- --coverage');
  process.exit(0);
}

const summary = readJson(COVERAGE_FILE);
const current = extractTotals(summary);
if (!current) {
  console.error(`❌ Cannot parse ${COVERAGE_FILE}. Run: npm run test -- --coverage`);
  process.exit(1);
}

const baseline = readJson(BASELINE_FILE);
if (!baseline) {
  console.log(`ℹ️  No baseline at ${BASELINE_FILE} — writing initial baseline from current coverage.`);
  const init = {
    _generated: new Date().toISOString(),
    _note: 'Auto-generated initial baseline. Update intentionally with --update.',
    statements: current.statements,
    branches: current.branches,
    functions: current.functions,
    lines: current.lines,
    uncoveredLines: current.uncoveredLines,
    totalStatements: current.statementsCount,
  };
  writeFileSync(BASELINE_FILE, JSON.stringify(init, null, 2) + '\n');
  console.log(`✅ Initial baseline created: ${current.statements.toFixed(1)}% statements`);
  process.exit(0);
}

const metrics = ['statements', 'branches', 'functions', 'lines'];
const regressions = [];
const improvements = [];

for (const m of metrics) {
  const cur = current[m] ?? 0;
  const base = baseline[m] ?? 0;
  const floor = ABSOLUTE_FLOOR[m] ?? 0;

  if (cur < floor) {
    regressions.push({ metric: m, current: cur, baseline: base, reason: `below absolute floor (${floor}%)` });
  } else if (cur < base - TOLERANCE_PCT) {
    regressions.push({ metric: m, current: cur, baseline: base, reason: `dropped ${(base - cur).toFixed(1)}% below baseline` });
  } else if (cur > base + 0.1) {
    improvements.push({ metric: m, current: cur, baseline: base });
  }
}

console.log('\n## Coverage Ratchet Report\n');
console.log('| Metric     | Baseline | Current | Status |');
console.log('|------------|----------|---------|--------|');
for (const m of metrics) {
  const cur = (current[m] ?? 0).toFixed(1);
  const base = (baseline[m] ?? 0).toFixed(1);
  const isRegression = regressions.some(r => r.metric === m);
  const isImprovement = improvements.some(r => r.metric === m);
  const status = isRegression ? '🔴 REGRESSION' : isImprovement ? '✅ improved' : '✓ stable';
  console.log(`| ${m.padEnd(10)} | ${base.padStart(7)}% | ${cur.padStart(6)}% | ${status} |`);
}

if (improvements.length > 0) {
  console.log(`\n💡 Coverage improved! Run --update to advance the baseline.`);
}

if (regressions.length > 0) {
  console.error(`\n❌ Coverage regression detected (tolerance: ±${TOLERANCE_PCT}%):\n`);
  for (const r of regressions) {
    console.error(`   🔴 ${r.metric}: ${r.current.toFixed(1)}% (${r.reason})`);
  }
  console.error('\nFix: add tests to recover coverage, then rerun.');
  console.error('To intentionally lower baseline: node scripts/check-coverage-ratchet.mjs --update');
  process.exit(1);
}

console.log(`\n✅ Coverage ratchet passed — ${current.statements.toFixed(1)}% statements (baseline: ${(baseline.statements ?? 0).toFixed(1)}%)`);
process.exit(0);
