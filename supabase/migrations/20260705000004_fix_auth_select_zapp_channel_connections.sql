-- ==========================================================================
-- Detectado via teste de penetracao (T25): security_invoker=ON nas views public
-- exige que o usuario chamador (authenticated) tenha SELECT na tabela zapp
-- subjacente, alem de SELECT na propria view.
--
-- Situacao antes do fix:
--   - public.channel_connections (view): authenticated = SELECT, INSERT, UPDATE, DELETE
--   - zapp.channel_connections (tabela): authenticated = INSERT, UPDATE, DELETE (sem SELECT!)
--   - Com security_invoker=ON na view, queries de authenticated falhavam com
--     'permission denied for table channel_connections'
--
-- Fix: adicionar SELECT para authenticated em zapp.channel_connections.
--   - RLS ainda controla o que cada usuario ve (USING(true) = todos authenticated)
--   - O grant nao expoe dados adicionais alem do que a view ja permitia antes
-- ==========================================================================
GRANT SELECT ON zapp.channel_connections TO authenticated;

